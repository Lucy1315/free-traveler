export type SafetyAlertLevel =
  "여행금지" | "출국권고" | "여행자제" | "여행유의" | "해당없음";

export type SafetyAlertScopeType = "국가전체" | "지역";

export interface SafetyAlert {
  level: SafetyAlertLevel;
  scopeType: SafetyAlertScopeType;
  scopeText: string;
  summary: string;
}

export type SafetyCategoryId =
  | "security"
  | "commonScams"
  | "localLaws"
  | "traffic"
  | "disasterAndClimate"
  | "health"
  | "cultureAndDress"
  | "emergencyContacts";

export interface SafetyCategory {
  id: SafetyCategoryId;
  title: string;
  items: string[];
}

export interface SafetyEmergencyContact {
  label: string;
  phone: string;
}

export interface SafetySource {
  name: string;
  url: string;
  verifiedAt: string; // ISO 8601 날짜(YYYY-MM-DD)
  editor: string;
}

export interface CountrySafety {
  country: string;
  continent: string;
  /** 가장 높은 단계의 경보(REQ-FUNC-051: 중대 경보를 상단에 표시). alerts[0]과 같다. */
  alert: SafetyAlert;
  /** 발령 중인 모든 경보, 높은 단계부터(REQ-FUNC-052: 국가 전체·특정 지역 범위 구분). */
  alerts: SafetyAlert[];
  categories: SafetyCategory[]; // 정확히 8개(REQ-FUNC-047)
  emergencyContacts: SafetyEmergencyContact[]; // 현지 긴급전화 + 재외공관/영사콜센터(REQ-FUNC-053)
  mofaUrl: string; // 외교부 해외안전여행 원문 링크(REQ-FUNC-049)
  source: SafetySource;
}

// REQ-FUNC-050: 최종 확인일(verifiedAt) 기준 7일 초과 시 stale로 판단한다.
// REQ-NF-028(축소): 경고 로직만 제공하며, 수치 목표는 검증하지 않는다.
export function isSafetyStale(
  verifiedAt: string,
  referenceDate: Date = new Date(),
): boolean {
  const verified = new Date(`${verifiedAt}T00:00:00`);
  const diffMs = referenceDate.getTime() - verified.getTime();
  const diffDays = diffMs / (1000 * 60 * 60 * 24);
  return diffDays > 7;
}

/** 중대 경보(출국권고·여행금지) 여부. 화면에서 강조 표시할 때 쓴다(REQ-FUNC-051). */
export function isSevereAlertLevel(level: SafetyAlertLevel): boolean {
  return level === "출국권고" || level === "여행금지";
}

const SOURCE_NAME = "외교부 해외안전여행";
const VERIFIED_AT = "2026-09-19";
const EDITOR = "free_traveler";

interface CountrySafetyInput {
  country: string;
  continent: string;
  /** 외교부 해외안전여행 국가 페이지 번호(/ntnSafetyInfo/<번호>/detail). */
  mofaCode: number;
  alerts: SafetyAlert[];
  security: string[];
  commonScams: string[];
  localLaws: string[];
  traffic: string[];
  disasterAndClimate: string[];
  health: string[];
  cultureAndDress: string[];
  emergencyContacts: SafetyEmergencyContact[];
}

function defineCountrySafety(input: CountrySafetyInput): CountrySafety {
  const url = `https://www.0404.go.kr/ntnSafetyInfo/${input.mofaCode}/detail`;
  return {
    country: input.country,
    continent: input.continent,
    alert: input.alerts[0],
    alerts: input.alerts,
    categories: [
      { id: "security", title: "치안", items: input.security },
      { id: "commonScams", title: "흔한 사기", items: input.commonScams },
      { id: "localLaws", title: "현지 법규", items: input.localLaws },
      { id: "traffic", title: "교통", items: input.traffic },
      {
        id: "disasterAndClimate",
        title: "재난·기후",
        items: input.disasterAndClimate,
      },
      { id: "health", title: "보건", items: input.health },
      {
        id: "cultureAndDress",
        title: "문화·복장",
        items: input.cultureAndDress,
      },
      {
        id: "emergencyContacts",
        title: "긴급연락처",
        items: input.emergencyContacts.map(
          (contact) => `${contact.label} ${contact.phone}`,
        ),
      },
    ],
    emergencyContacts: input.emergencyContacts,
    mofaUrl: url,
    source: { name: SOURCE_NAME, url, verifiedAt: VERIFIED_AT, editor: EDITOR },
  };
}

